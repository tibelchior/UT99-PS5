    f.write("// Generated by tools/make_kbfont.py: 5x8 glyphs for the on-screen keyboard (bit 4 = leftmost pixel).\n")
    f.write("#pragma once\n#include <cstdint>\n")
    f.write("static const uint8_t kKbFont[128][8] = {\n")
